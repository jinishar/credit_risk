"""Evaluation metrics for the imbalanced binary default-prediction task.

Accuracy is intentionally NOT the headline metric: with ~87/13 class split, a
model that always predicts "no default" scores ~87% accuracy while being
useless. ROC-AUC and PR-AUC (average precision) are threshold-independent and
sensitive to how well the minority (default) class is ranked, which is what
actually matters for credit risk triage.
"""
from __future__ import annotations

import numpy as np
from sklearn.metrics import (
    average_precision_score,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
)


def evaluate(y_true: np.ndarray, y_prob: np.ndarray, threshold: float = 0.5) -> dict:
    y_pred = (y_prob >= threshold).astype(int)
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred).ravel()
    return {
        "roc_auc": float(roc_auc_score(y_true, y_prob)),
        "pr_auc": float(average_precision_score(y_true, y_prob)),
        "f1": float(f1_score(y_true, y_pred, zero_division=0)),
        "precision": float(precision_score(y_true, y_pred, zero_division=0)),
        "recall": float(recall_score(y_true, y_pred, zero_division=0)),
        "threshold": threshold,
        "confusion_matrix": {
            "true_negative": int(tn), "false_positive": int(fp),
            "false_negative": int(fn), "true_positive": int(tp),
        },
        "positive_rate": float(y_true.mean()),
        "n_samples": int(len(y_true)),
    }
